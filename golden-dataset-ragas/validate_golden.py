import json
import random
import sqlite3
import sys

import pandas as pd
from pypdf import PdfReader

from build_golden import (BASE, CSV_PATH, CSV_QS, DB_PATH, IDK, OUT, PDF_DIR,
                          PDF_SPEC, SQL_QS, fmt, sql_answer)

rows = [json.loads(l) for l in OUT.read_text(encoding="utf-8").splitlines() if l.strip()]
errors = []


def check(cond, msg):
    if not cond:
        errors.append(msg)


# ---- structure checks
check(len(rows) == 30, f"Expected 30 rows, got {len(rows)}")
check(len({r["question"] for r in rows}) == len(rows), "Duplicate questions found")
for r in rows:
    check(set(r) == {"question", "ground_truth", "source", "page"}, f"Bad fields: {r}")
n_pdf = sum(r["source"].endswith(".pdf") for r in rows)
n_csv = sum(r["source"].endswith(".csv") for r in rows)
n_sql = sum(r["source"].startswith("mock_db") for r in rows)
n_idk = sum(r["ground_truth"] == IDK for r in rows)
check((n_pdf, n_csv, n_sql) == (15, 8, 7), f"Split wrong: pdf={n_pdf} csv={n_csv} sql={n_sql}")
check(n_idk == 5, f"Expected 5 unanswerable, got {n_idk}")

# ---- answer checks against the real sources
pdf_keys = {q: (f, pn, key) for f, pages in PDF_SPEC.items()
            for pn, page in enumerate(pages, 1) for _, q, _, key in page if q}
csv_fn = dict(CSV_QS)
sql_map = dict(SQL_QS)
df = pd.read_csv(CSV_PATH)
cur = sqlite3.connect(DB_PATH).cursor()

for r in rows:
    q = r["question"]
    if r["ground_truth"] == IDK:
        continue
    if q in pdf_keys:
        f, pn, key = pdf_keys[q]
        check(r["source"] == f and r["page"] == pn, f"Source/page mismatch: {q}")
        text = " ".join(PdfReader(PDF_DIR / f).pages[pn - 1].extract_text().split()).lower()
        check(key.lower() in text, f"'{key}' NOT found on {f} page {pn}")
    elif q in csv_fn:
        check(fmt(csv_fn[q](df)) == r["ground_truth"], f"CSV answer mismatch: {q}")
    elif q in sql_map:
        check(sql_answer(cur, sql_map[q]) == r["ground_truth"], f"SQL answer mismatch: {q}")
    else:
        errors.append(f"Question not traceable to a source: {q}")

# unanswerable questions must NOT be answerable from the source text
all_pdf_text = " ".join(
    " ".join(PdfReader(PDF_DIR / f).pages[i].extract_text().split()).lower()
    for f in PDF_SPEC for i in range(len(PDF_SPEC[f])))
for bad in ["sabbatical", "firewall", "hotel"]:
    check(bad not in all_pdf_text, f"Unanswerable topic '{bad}' appears in a PDF")

if errors:
    print("FAILED:")
    for e in errors:
        print(" -", e)
    sys.exit(1)

print("ALL CHECKS PASSED: 30 rows | PDF 15, CSV 8, SQL 7 | 5 unanswerable")

# ---- peer review sheet (10 questions: 8 answerable + 2 unanswerable)
rnd = random.Random(42)
answerable = [r for r in rows if r["ground_truth"] != IDK]
unans = [r for r in rows if r["ground_truth"] == IDK]
sample = rnd.sample(answerable, 8) + rnd.sample(unans, 2)
lines = ["# Peer Review Sheet (10 questions)", "",
         "Reviewer name: ____________   Date: ________", "",
         "| # | Question | Ground truth | Source (page) | Clear? (Y/N) | Correct? (Y/N) | Comment |",
         "|---|----------|--------------|---------------|--------------|----------------|---------|"]
for i, r in enumerate(sample, 1):
    pg = f" (p.{r['page']})" if r["page"] else ""
    lines.append(f"| {i} | {r['question']} | {r['ground_truth']} | {r['source']}{pg} | | | |")
(BASE / "peer_review_sheet.md").write_text("\n".join(lines), encoding="utf-8")

# ---- validation note (fill the peer review part after your reviewer is done)
note = f"""# Validation Note - golden_30.jsonl

## How I validated the answers
1. Source files were generated by script (3 PDFs, products.csv, mock_db.sqlite), so every fact has a known location.
2. Structure check: 30 rows, fields question/ground_truth/source/page, no duplicate questions.
   Split: PDF {n_pdf}, CSV {n_csv}, SQL {n_sql}. Unanswerable ("I don't know"): {n_idk}.
3. PDF answers: validate_golden.py extracts the text of the stated page with pypdf and confirms the answer
   phrase appears on exactly that page.
4. CSV answers: recomputed from products.csv with pandas and compared with ground_truth.
5. SQL answers: re-run the SQL query on mock_db.sqlite and compared with ground_truth.
6. Unanswerable questions: confirmed the topic does not appear anywhere in the sources.
7. Peer review: 10 questions (8 answerable + 2 unanswerable) reviewed by ____________ using peer_review_sheet.md.
   Result: __ of 10 clear, __ of 10 correct. Changes made after review: ____________.

All {len(rows)} automatic checks passed.
"""
(BASE / "validation_note.md").write_text(note, encoding="utf-8")
print("Created peer_review_sheet.md and validation_note.md")